    private void carregarBoletosPagamentos() {

    String sql = "SELECT b.id_boleto, b.valor, b.data_vencimento, b.status, "
            + "p.data_pagamento, p.valor_pago "
            + "FROM boleto b "
            + "INNER JOIN aluguel a ON b.id_aluguel = a.id_aluguel "
            + "LEFT JOIN pagamento p ON a.id_aluguel = p.id_aluguel "
            + "INNER JOIN contrato c ON a.id_contrato = c.id_contrato "
            + "WHERE c.id_inquilino = ?";

    try (Connection conexao = Conexao.conectar();
         PreparedStatement stmt = conexao.prepareStatement(sql)) {

        stmt.setInt(1, Sessao.idInquilino);

        ResultSet resultado = stmt.executeQuery();

        String texto = "========================================\n"
                + "        MEUS BOLETOS E PAGAMENTOS\n"
                + "========================================\n\n";

        boolean encontrou = false;

        while (resultado.next()) {

            encontrou = true;

            texto += "Boleto: " + resultado.getInt("id_boleto") + "\n";
            texto += "Valor: R$ " + resultado.getDouble("valor") + "\n";
            texto += "Vencimento: " + resultado.getDate("data_vencimento") + "\n";
            texto += "Status: " + resultado.getString("status") + "\n";

            if (resultado.getDate("data_pagamento") != null) {
                texto += "Data do pagamento: "
                        + resultado.getDate("data_pagamento") + "\n";
                texto += "Valor pago: R$ "
                        + resultado.getDouble("valor_pago") + "\n";
            } else {
                texto += "Pagamento: Ainda nao realizado\n";
            }

            texto += "\n----------------------------------------\n\n";
        }

        if (!encontrou) {
            texto += "Nenhum boleto encontrado.";
        }

        txtBoletos.setText(texto);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao carregar boletos e pagamentos: " + e.getMessage());
    }
}

