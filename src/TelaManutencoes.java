    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    DefaultTableModel modelo = new DefaultTableModel(
    new Object[]{"ID", "IMOVEL", "INQUILINO", "DESCRICAO",
                 "DATA", "STATUS"}, 0
);

String sql = "SELECT m.id_manutencao, m.id_imovel, i.nome, " +
             "m.descricao, m.data_solicitacao, m.status " +
             "FROM manutencao m " +
             "INNER JOIN imovel im ON m.id_imovel = im.id_imovel " +
             "INNER JOIN inquilino i ON m.id_inquilino = i.id_inquilino " +
             "WHERE im.id_proprietario = ? " +
             "ORDER BY m.data_solicitacao DESC";

try (Connection conexao = Conexao.conectar();
     PreparedStatement stmt = conexao.prepareStatement(sql)) {

    stmt.setInt(1, Sessao.idProprietario);

    try (ResultSet rs = stmt.executeQuery()) {
        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getInt("id_manutencao"),
                rs.getInt("id_imovel"),
                rs.getString("nome"),
                rs.getString("descricao"),
                rs.getDate("data_solicitacao"),
                rs.getString("status")
            });
        }
    }

    jTable1.setModel(modelo);

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this, "Erro ao listar manutencoes: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
      int linha = jTable1.getSelectedRow();

if (linha == -1) {
    JOptionPane.showMessageDialog(
        this,
        "Selecione uma manutencao na tabela."
    );
    return;
}

int idManutencao = Integer.parseInt(
    jTable1.getValueAt(linha, 0).toString()
);

String novoStatus = jComboBox1.getSelectedItem().toString();

String sql = "UPDATE manutencao m " +
             "INNER JOIN imovel im ON m.id_imovel = im.id_imovel " +
             "SET m.status = ? " +
             "WHERE m.id_manutencao = ? " +
             "AND im.id_proprietario = ?";

try (Connection conexao = Conexao.conectar();
     PreparedStatement stmt = conexao.prepareStatement(sql)) {

    stmt.setString(1, novoStatus);
    stmt.setInt(2, idManutencao);
    stmt.setInt(3, Sessao.idProprietario);

    int linhasAlteradas = stmt.executeUpdate();

    if (linhasAlteradas > 0) {
        JOptionPane.showMessageDialog(
            this,
            "Status atualizado com sucesso!"
        );
    } else {
        JOptionPane.showMessageDialog(
            this,
            "Manutencao nao encontrada para este proprietario."
        );
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this,
        "Erro ao atualizar status: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jButton2ActionPerformed

