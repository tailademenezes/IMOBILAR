    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
     String textoIdImovel = jTextField6.getText().trim();
String descricao = jTextField5.getText().trim();
String data = jTextField4.getText().trim();
String status = jComboBox1.getSelectedItem().toString();

if (textoIdImovel.isEmpty() || descricao.isEmpty() || data.isEmpty()) {
    JOptionPane.showMessageDialog(
        this, "Preencha o ID do imovel, a descricao e a data."
    );
    return;
}

int idImovel;

try {
    idImovel = Integer.parseInt(textoIdImovel);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Digite um ID de imovel valido.");
    return;
}

java.sql.Date dataSolicitacao;

try {
    java.text.SimpleDateFormat formato =
            new java.text.SimpleDateFormat("dd/MM/yyyy");

    formato.setLenient(false);

    java.util.Date dataConvertida = formato.parse(data);

    dataSolicitacao =
            new java.sql.Date(dataConvertida.getTime());

} catch (java.text.ParseException e) {
    JOptionPane.showMessageDialog(
        this, "Digite a data no formato DD/MM/AAAA."
    );
    return;
}
String sql = "INSERT INTO manutencao " +
             "(id_imovel, id_inquilino, descricao, data_solicitacao, status) " +
             "SELECT im.id_imovel, i.id_inquilino, ?, ?, ? " +
             "FROM imovel im " +
             "INNER JOIN inquilino i ON i.id_imovel = im.id_imovel " +
             "WHERE im.id_imovel = ? " +
             "AND im.id_proprietario = ?";

try (Connection conexao = Conexao.conectar();
     PreparedStatement stmt = conexao.prepareStatement(sql)) {

    stmt.setString(1, descricao);
    stmt.setDate(2, dataSolicitacao);
    stmt.setString(3, status);
    stmt.setInt(4, idImovel);
    stmt.setInt(5, Sessao.idProprietario);

    int resultado = stmt.executeUpdate();

    if (resultado > 0) {
        JOptionPane.showMessageDialog(
            this, "Manutencao cadastrada com sucesso!"
        );

      
    } else {
        JOptionPane.showMessageDialog(
            this,
            "Nao foi possivel cadastrar. Confira se o imovel pertence " +
            "ao proprietario e possui um inquilino vinculado."
        );
    }

} catch (Exception e) {
    JOptionPane.showMessageDialog(
        this, "Erro ao cadastrar manutencao: " + e.getMessage()
    );
}
    }//GEN-LAST:event_jButton5ActionPerformed

