    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
     DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();

modelo.setRowCount(0);

try {

    Connection conexao = Conexao.conectar();

    String sql = "SELECT id_imovel, endereco, tipo_imovel, valor_aluguel "
            + "FROM imovel "
            + "WHERE id_proprietario = ?";

    PreparedStatement stmt = conexao.prepareStatement(sql);

    stmt.setInt(1, Sessao.idProprietario);

    ResultSet resultado = stmt.executeQuery();

    while (resultado.next()) {

        modelo.addRow(new Object[]{
            resultado.getInt("id_imovel"),
            resultado.getString("endereco"),
            resultado.getString("tipo_imovel"),
            resultado.getDouble("valor_aluguel")
        });
    }

} catch (Exception e) {

    JOptionPane.showMessageDialog(this, "Erro ao listar imoveis!");
    e.printStackTrace();
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
String id = jTextField1.getText();
String endereco = jTextField2.getText();
String valor = jTextField3.getText();

try {
    Integer.parseInt(id);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Digite um ID valido!");
    return;
}

try {
    Double.parseDouble(valor);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Digite um valor valido!");
    return;
}

String tipo = jComboBox1.getSelectedItem().toString();

try {

    Connection conexao = Conexao.conectar();

    String sql = "INSERT INTO imovel "
            + "(id_imovel, id_proprietario, endereco, tipo_imovel, valor_aluguel, status) "
            + "VALUES (?, ?, ?, ?, ?, ?)";

    PreparedStatement stmt = conexao.prepareStatement(sql);

    stmt.setInt(1, Integer.parseInt(id));
    stmt.setInt(2, Sessao.idProprietario);
    stmt.setString(3, endereco);
    stmt.setString(4, tipo);
    stmt.setDouble(5, Double.parseDouble(valor));
    stmt.setString(6, "Disponivel");

    stmt.executeUpdate();

    JOptionPane.showMessageDialog(this, "Imovel cadastrado com sucesso!");

} catch (Exception e) {

    JOptionPane.showMessageDialog(this, "Erro ao cadastrar imovel!");
    e.printStackTrace();
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
 

    int linhaSelecionada = jTable1.getSelectedRow();

    if (linhaSelecionada == -1) {
        JOptionPane.showMessageDialog(this,
                "Selecione um imovel na tabela!");
        return;
    }

    int idImovel = Integer.parseInt(
            jTable1.getValueAt(linhaSelecionada, 0).toString()
    );

    int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir este imovel?",
            "Confirmacao",
            JOptionPane.YES_NO_OPTION
    );

    if (resposta != JOptionPane.YES_OPTION) {
        return;
    }

    try {

        Connection conexao = Conexao.conectar();

        String sql = "DELETE FROM imovel "
                + "WHERE id_imovel = ? "
                + "AND id_proprietario = ?";

        PreparedStatement stmt = conexao.prepareStatement(sql);

        stmt.setInt(1, idImovel);
        stmt.setInt(2, Sessao.idProprietario);

        int linhasAfetadas = stmt.executeUpdate();

        if (linhasAfetadas > 0) {

            JOptionPane.showMessageDialog(this,
                    "Imovel excluido com sucesso!");

            ((DefaultTableModel) jTable1.getModel())
                    .removeRow(linhaSelecionada);

        } else {

            JOptionPane.showMessageDialog(this,
                    "Imovel nao encontrado!");
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Erro ao excluir imovel!");
        e.printStackTrace();
    }

    }//GEN-LAST:event_jButton3ActionPerformed

