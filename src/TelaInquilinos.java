    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
  String idImovel = jTextField1.getText();
String nome = jTextField4.getText();
String cpf = jTextField3.getText();
String telefone = jTextField2.getText();
String email = jTextField5.getText();

if (idImovel.isEmpty() || nome.trim().isEmpty()
        || cpf.isEmpty() || telefone.isEmpty() || email.isEmpty()) {

    JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
    return;
}

try {

    int id = Integer.parseInt(idImovel);

    Connection conexao = Conexao.conectar();

    // Verifica se o imovel existe
    String sqlImovel = "SELECT id_imovel FROM imovel "
            + "WHERE id_imovel = ? "
            + "AND id_proprietario = ?";

    PreparedStatement stmtImovel = conexao.prepareStatement(sqlImovel);

    stmtImovel.setInt(1, id);
    stmtImovel.setInt(2, Sessao.idProprietario);

    ResultSet resultado = stmtImovel.executeQuery();

    if (!resultado.next()) {

        JOptionPane.showMessageDialog(this,
                "Imovel nao encontrado ou nao pertence a este proprietario!");

        return;
    }

    // Cadastra o inquilino
    String sql = "INSERT INTO inquilino "
            + "(id_imovel, nome, cpf, telefone, email) "
            + "VALUES (?, ?, ?, ?, ?)";

    PreparedStatement stmt = conexao.prepareStatement(sql);

    stmt.setInt(1, id);
    stmt.setString(2, nome);
    stmt.setString(3, cpf);
    stmt.setString(4, telefone);
    stmt.setString(5, email);

    stmt.executeUpdate();

    JOptionPane.showMessageDialog(this,
            "Inquilino cadastrado com sucesso!");

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(this,
            "Digite um ID de imovel valido!");

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            "Erro ao cadastrar inquilino!");

    e.printStackTrace();
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
    DefaultTableModel modelo = new DefaultTableModel(
        new Object[][]{},
        new String[]{
            "ID Inquilino",
            "ID Imovel",
            "Nome",
            "CPF",
            "Telefone",
            "E-mail"
        }
);

jTable2.setModel(modelo);
jTable2.setAutoCreateColumnsFromModel(true);

try {

    Connection conexao = Conexao.conectar();

    String sql = "SELECT i.id_inquilino, i.id_imovel, i.nome, "
            + "i.cpf, i.telefone, i.email "
            + "FROM inquilino i "
            + "INNER JOIN imovel im ON i.id_imovel = im.id_imovel "
            + "WHERE im.id_proprietario = ?";

    PreparedStatement stmt = conexao.prepareStatement(sql);

    stmt.setInt(1, 1);

    ResultSet resultado = stmt.executeQuery();

    while (resultado.next()) {

        modelo.addRow(new Object[]{
            resultado.getInt("id_inquilino"),
            resultado.getInt("id_imovel"),
            resultado.getString("nome"),
            resultado.getString("cpf"),
            resultado.getString("telefone"),
            resultado.getString("email")
        });
    }
    jTable2.revalidate();
jTable2.repaint();

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            "Erro ao listar inquilinos!");

    e.printStackTrace();
}
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
 

    int linhaSelecionada = jTable2.getSelectedRow();

    if (linhaSelecionada == -1) {
        JOptionPane.showMessageDialog(this,
                "Selecione um inquilino na tabela!");
        return;
    }

    int idInquilino = Integer.parseInt(
            jTable2.getValueAt(linhaSelecionada, 0).toString()
    );

    int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir este inquilino?",
            "Confirmacao",
            JOptionPane.YES_NO_OPTION
    );

    if (resposta != JOptionPane.YES_OPTION) {
        return;
    }

    try {
        Connection conexao = Conexao.conectar();

        String sql = "DELETE FROM inquilino WHERE id_inquilino = ?";

        PreparedStatement stmt = conexao.prepareStatement(sql);

        stmt.setInt(1, idInquilino);

        int linhasAfetadas = stmt.executeUpdate();

        if (linhasAfetadas > 0) {

            JOptionPane.showMessageDialog(this,
                    "Inquilino excluido com sucesso!");

            ((DefaultTableModel) jTable1.getModel())
                    .removeRow(linhaSelecionada);

        } else {

            JOptionPane.showMessageDialog(this,
                    "Inquilino nao encontrado!");
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Erro ao excluir inquilino!");

        e.printStackTrace();
    }

    }//GEN-LAST:event_jButton2ActionPerformed

