    escolhaArquivo.setDialogTitle("Salvar contrato em PDF");

    escolhaArquivo.setSelectedFile(
            new java.io.File("Contrato_" + idInquilinoNumero + ".pdf")
    );

    int resposta = escolhaArquivo.showSaveDialog(this);

