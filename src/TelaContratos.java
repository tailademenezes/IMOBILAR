    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
 try {
    Connection conexao = Conexao.conectar();

    if (conexao == null) {
        JOptionPane.showMessageDialog(this,
                "Erro ao conectar ao banco de dados!");
        return;
    }

    String sql = "SELECT c.id_contrato, c.id_imovel, "
            + "i.nome AS inquilino, c.valor_aluguel, "
            + "c.data_inicio, c.data_fim, c.vencimento, c.status "
            + "FROM contrato c "
            + "INNER JOIN inquilino i "
            + "ON c.id_inquilino = i.id_inquilino "
            + "INNER JOIN imovel im "
            + "ON c.id_imovel = im.id_imovel "
            + "WHERE im.id_proprietario = ?";

    PreparedStatement stmt = conexao.prepareStatement(sql);
    stmt.setInt(1, Sessao.idProprietario);

    ResultSet resultado = stmt.executeQuery();

    StringBuilder lista = new StringBuilder();

    while (resultado.next()) {
        lista.append("CONTRATO: ")
                .append(resultado.getInt("id_contrato"))
                .append("\nImovel: ")
                .append(resultado.getInt("id_imovel"))
                .append("\nInquilino: ")
                .append(resultado.getString("inquilino"))
                .append("\nValor: R$ ")
                .append(resultado.getDouble("valor_aluguel"))
                .append("\nInicio: ")
                .append(resultado.getDate("data_inicio"))
                .append("\nTermino: ")
                .append(resultado.getDate("data_fim"))
                .append("\nVencimento: dia ")
                .append(resultado.getInt("vencimento"))
                .append("\nStatus: ")
                .append(resultado.getString("status"))
                .append("\n-----------------------------\n");
    }

    if (lista.length() == 0) {
        JOptionPane.showMessageDialog(this,
                "Nenhum contrato cadastrado.");
    } else {
        javax.swing.JTextArea area =
                new javax.swing.JTextArea(lista.toString(), 20, 45);

        area.setEditable(false);
        area.setCaretPosition(0);

        javax.swing.JScrollPane rolagem =
                new javax.swing.JScrollPane(area);

        JOptionPane.showMessageDialog(this,
                rolagem, "CONTRATOS CADASTRADOS",
                JOptionPane.INFORMATION_MESSAGE);
    }

    resultado.close();
    stmt.close();
    conexao.close();

} catch (Exception e) {
    JOptionPane.showMessageDialog(this,
            "Erro ao listar contratos!");
    e.printStackTrace();
}
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
      String idTexto = JOptionPane.showInputDialog(
        this, "Digite o ID do contrato que deseja excluir:");

if (idTexto == null || idTexto.trim().isEmpty()) {
    return;
}

try {
    int idContrato = Integer.parseInt(idTexto.trim());

    int confirmacao = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir este contrato?",
            "Confirmar exclusao",
            JOptionPane.YES_NO_OPTION
    );

    if (confirmacao != JOptionPane.YES_OPTION) {
        return;
    }

    Connection conexao = Conexao.conectar();

    if (conexao == null) {
        JOptionPane.showMessageDialog(this,
                "Erro ao conectar ao banco de dados!");
        return;
    }

    String sql = "DELETE c FROM contrato c "
            + "INNER JOIN imovel i ON c.id_imovel = i.id_imovel "
            + "WHERE c.id_contrato = ? "
            + "AND i.id_proprietario = ?";

    PreparedStatement stmt = conexao.prepareStatement(sql);
    stmt.setInt(1, idContrato);
    stmt.setInt(2, Sessao.idProprietario);

    int linhas = stmt.executeUpdate();

    if (linhas > 0) {
        JOptionPane.showMessageDialog(this,
                "Contrato excluido com sucesso!");
    } else {
        JOptionPane.showMessageDialog(this,
                "Contrato nao encontrado para este proprietario.");
    }

    stmt.close();
    conexao.close();

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Digite um ID numerico!");

} catch (Exception e) {
    JOptionPane.showMessageDialog(this,
            "Erro ao excluir contrato!");
    e.printStackTrace();
}
    }//GEN-LAST:event_jButton4ActionPerformed

