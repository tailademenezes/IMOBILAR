    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
  String nome = jTextField1.getText();
String cpf = jTextField2.getText();
String email = jTextField3.getText();

String senha = new String(jPasswordField1.getPassword());
String confirmarSenha = new String(jPasswordField2.getPassword());

if (nome.trim().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Digite seu nome!");
    return;
}

if (!cpf.matches("\\d+")) {
    JOptionPane.showMessageDialog(this, "O CPF deve conter apenas numeros!");
    return;
}

if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
    JOptionPane.showMessageDialog(this, "Digite um email valido!");
    return;
}

if (senha.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Digite uma senha!");
    return;
}

if (!senha.equals(confirmarSenha)) {
    JOptionPane.showMessageDialog(this, "As senhas nao coincidem!");
    return;
}

try {

    Connection conexao = Conexao.conectar();

    String sql = "SELECT id_inquilino FROM inquilino WHERE cpf = ?";

    PreparedStatement stmt = conexao.prepareStatement(sql);
    stmt.setString(1, cpf);

    ResultSet resultado = stmt.executeQuery();

    if (!resultado.next()) {

        JOptionPane.showMessageDialog(this, "CPF nao encontrado. Cadastro nao permitido!");
        return;
    }

    int idInquilino = resultado.getInt("id_inquilino");

    String sqlCadastro = "INSERT INTO usuario "
            + "(nome, email, senha, tipo_usuario, id_inquilino) "
            + "VALUES (?, ?, ?, ?, ?)";

    PreparedStatement stmtCadastro = conexao.prepareStatement(sqlCadastro);

    stmtCadastro.setString(1, nome);
    stmtCadastro.setString(2, email);
    stmtCadastro.setString(3, senha);
    stmtCadastro.setString(4, "inquilino");
    stmtCadastro.setInt(5, idInquilino);

    stmtCadastro.executeUpdate();

    JOptionPane.showMessageDialog(this, "Cadastro realizado com sucesso!");

} catch (Exception e) {

    JOptionPane.showMessageDialog(this, "Erro ao realizar cadastro!");
    e.printStackTrace();
}
    }//GEN-LAST:event_jButton1ActionPerformed

