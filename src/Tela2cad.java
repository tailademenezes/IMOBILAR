    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
  String email = jTextField1.getText();
String cpf = jTextField2.getText();
String senha = new String(jPasswordField1.getPassword());

if (!cpf.matches("\\d+")) {
    JOptionPane.showMessageDialog(this, "O CPF deve conter apenas numeros!");
    return;
}

if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
    JOptionPane.showMessageDialog(this, "Digite um email valido!");
    return;
}

if (senha.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Digite sua senha!");
    return;
}

try {

    Connection conexao = Conexao.conectar();

    // Verifica se e proprietario
    String sqlProprietario = "SELECT * FROM proprietario "
            + "WHERE email = ? AND cpf = ? AND senha = ?";

    PreparedStatement stmtProprietario = conexao.prepareStatement(sqlProprietario);

    stmtProprietario.setString(1, email);
    stmtProprietario.setString(2, cpf);
    stmtProprietario.setString(3, senha);

    ResultSet resultadoProprietario = stmtProprietario.executeQuery();

    if (resultadoProprietario.next()) {

    int idProprietario = resultadoProprietario.getInt("id_proprietario");
 Sessao.idProprietario = idProprietario;
    tela3prop tela = new tela3prop();
    tela.setVisible(true);
    this.dispose();
    return;
}

    // Verifica se e inquilino
    String sqlInquilino = "SELECT tipo_usuario FROM usuario "
            + "WHERE email = ? AND senha = ? "
            + "AND id_inquilino = ("
            + "SELECT id_inquilino FROM inquilino WHERE cpf = ?"
            + ")";

    PreparedStatement stmtInquilino = conexao.prepareStatement(sqlInquilino);

    stmtInquilino.setString(1, email);
    stmtInquilino.setString(2, senha);
    stmtInquilino.setString(3, cpf);

    ResultSet resultadoInquilino = stmtInquilino.executeQuery();

    if (resultadoInquilino.next()) {

         String sqlId = "SELECT id_inquilino FROM inquilino WHERE cpf = ?";

    PreparedStatement stmtId = conexao.prepareStatement(sqlId);
    stmtId.setString(1, cpf);

    ResultSet resultadoId = stmtId.executeQuery();

    if (resultadoId.next()) {
        Sessao.idInquilino = resultadoId.getInt("id_inquilino");
    }

    Tela4menuinq tela = new Tela4menuinq();
        tela.setVisible(true);
        this.dispose();

    } else {

        JOptionPane.showMessageDialog(this, "Alguma informacao esta invalida!");
    }

} catch (Exception e) {

    JOptionPane.showMessageDialog(this, "Erro ao realizar login!");
    e.printStackTrace();
}
    }//GEN-LAST:event_jButton1ActionPerformed

