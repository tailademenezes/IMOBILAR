private void carregarManutencoes() {

    String sql = "SELECT descricao, data_solicitacao, status "
            + "FROM manutencao "
            + "WHERE id_inquilino = ? "
            + "ORDER BY data_solicitacao DESC";

    try (Connection conexao = Conexao.conectar();
         PreparedStatement stmt = conexao.prepareStatement(sql)) {

        stmt.setInt(1, Sessao.idInquilino);

        ResultSet resultado = stmt.executeQuery();

        String texto = "";

        while (resultado.next()) {

            texto += "Problema: "
                    + resultado.getString("descricao") + "\n";

            texto += "Data: "
                    + resultado.getDate("data_solicitacao") + "\n";

            texto += "Status: "
                    + resultado.getString("status") + "\n";

            texto += "----------------------------------------\n\n";
        }

        if (texto.isEmpty()) {
            texto = "Nenhuma solicitacao de manutencao encontrada.";
        }

        txtManutencoes.setText(texto);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao carregar manutencoes: " + e.getMessage());
    }
}
