    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
     String problema = txtProblema.getText().trim();

if (problema.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Digite o problema!");
    return;
}

String sql = "INSERT INTO manutencao "
        + "(id_imovel, id_inquilino, descricao, data_solicitacao, status) "
        + "SELECT c.id_imovel, ?, ?, CURDATE(), 'Pendente' "
        + "FROM contrato c "
        + "WHERE c.id_inquilino = ? "
        + "LIMIT 1";

try (Connection conexao = Conexao.conectar();
     PreparedStatement stmt = conexao.prepareStatement(sql)) {

    stmt.setInt(1, Sessao.idInquilino);
    stmt.setString(2, problema);
    stmt.setInt(3, Sessao.idInquilino);

    int resultado = stmt.executeUpdate();

    if (resultado > 0) {

        JOptionPane.showMessageDialog(this,
                "Solicitacao enviada com sucesso!");

        txtProblema.setText("");

        carregarManutencoes();
    }

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            "Erro ao enviar solicitacao: " + e.getMessage());
}
    }//GEN-LAST:event_jButton1ActionPerformed

