   private void carregarContrato() {
    String sql = "SELECT c.id_contrato, i.nome, im.endereco, "
            + "c.valor_aluguel, c.data_inicio, c.data_fim, "
            + "c.vencimento, c.status "
            + "FROM contrato c "
            + "INNER JOIN inquilino i ON c.id_inquilino = i.id_inquilino "
            + "INNER JOIN imovel im ON c.id_imovel = im.id_imovel "
            + "WHERE c.id_inquilino = ?";

    try (Connection conexao = Conexao.conectar();
         PreparedStatement stmt = conexao.prepareStatement(sql)) {
stmt.setInt(1, Sessao.idInquilino);
       

        try (ResultSet resultado = stmt.executeQuery()) {

            if (resultado.next()) {

                String contrato = "========================================\n"
                        + "              MEU CONTRATO\n"
                        + "========================================\n\n"
                        + "Numero do contrato: " + resultado.getInt("id_contrato") + "\n"
                        + "Inquilino: " + resultado.getString("nome") + "\n"
                        + "Endereco: " + resultado.getString("endereco") + "\n"
                        + "Valor do aluguel: R$ " + resultado.getDouble("valor_aluguel") + "\n"
                        + "Data de inicio: " + resultado.getDate("data_inicio") + "\n"
                        + "Data de fim: " + resultado.getDate("data_fim") + "\n"
                        + "Dia de vencimento: " + resultado.getInt("vencimento") + "\n"
                        + "Status: " + resultado.getString("status") + "\n";

                txtContrato.setText(contrato);

            } else {
                txtContrato.setText("Nenhum contrato encontrado.");
            }

        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Erro ao carregar contrato: " + e.getMessage());
    }
}

    

