private void carregarManutencoes() {

    String sql = "SELECT id_manutencao, descricao, data_solicitacao, status "
            + "FROM manutencao "
            + "WHERE id_inquilino = ? "
            + "ORDER BY data_solicitacao DESC";

    try (Connection conexao = Conexao.conectar();
         PreparedStatement stmt = conexao.prepareStatement(sql)) {

        stmt.setInt(1, Sessao.idInquilino);

        ResultSet resultado = stmt.executeQuery();

        txtManutencoes.setText("");
        comboManutencao.removeAllItems();

        while (resultado.next()) {

            int id = resultado.getInt("id_manutencao");
            String descricao = resultado.getString("descricao");
            String data = resultado.getString("data_solicitacao");
            String status = resultado.getString("status");

            txtManutencoes.append(
                    "Manutencao: " + id + "\n"
                    + "Problema: " + descricao + "\n"
                    + "Data: " + data + "\n"
                    + "Status: " + status + "\n"
                    + "----------------------------------------\n\n"
            );

            comboManutencao.addItem(
                    id + " - " + descricao
            );
        }

        if (comboManutencao.getItemCount() == 0) {
            txtManutencoes.setText(
                    "Nenhuma solicitacao de manutencao encontrada."
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(this,
                "Erro ao carregar manutencoes: " + e.getMessage());
    }
}
