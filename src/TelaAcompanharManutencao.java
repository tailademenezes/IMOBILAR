    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
  int indice = comboManutencao.getSelectedIndex();

if (indice == -1) {
    JOptionPane.showMessageDialog(this,
            "Selecione uma manutencao!");
    return;
}

String itemSelecionado = comboManutencao.getSelectedItem().toString();
int idManutencao = Integer.parseInt(
        itemSelecionado.substring(0, itemSelecionado.indexOf(" - "))
);

String novoStatus = comboStatus.getSelectedItem().toString();

String sql = "UPDATE manutencao "
        + "SET status = ? "
        + "WHERE id_manutencao = ? "
        + "AND id_inquilino = ?";

try (Connection conexao = Conexao.conectar();
     PreparedStatement stmt = conexao.prepareStatement(sql)) {

    stmt.setString(1, novoStatus);
    stmt.setInt(2, idManutencao);
    stmt.setInt(3, Sessao.idInquilino);

    int resultado = stmt.executeUpdate();

    if (resultado > 0) {

        JOptionPane.showMessageDialog(this,
                "Status atualizado com sucesso!");

        carregarManutencoes();

    } else {

        JOptionPane.showMessageDialog(this,
                "Manutencao nao encontrada.");
    }

} catch (Exception e) {

    JOptionPane.showMessageDialog(this,
            "Erro ao atualizar status: " + e.getMessage());
}
    }//GEN-LAST:event_jButton1ActionPerformed

